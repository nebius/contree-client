// Command docgen renders a Go package as a MyST page for Sphinx.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/doc"
	"go/doc/comment"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	dir := flag.String("dir", "./v1", "Go package source directory")
	importPath := flag.String("import-path", "", "Go package import path")
	output := flag.String("output", "", "Output MyST Markdown file")
	flag.Parse()
	if *importPath == "" || *output == "" {
		log.Fatal("-import-path and -output are required")
	}

	page, err := generate(*dir, *importPath)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*output, page, 0o644); err != nil {
		log.Fatal(err)
	}
}

func generate(dir, importPath string) ([]byte, error) {
	// Respect build constraints, and include test files so go/doc can associate
	// executable examples with their public types and methods.
	pkg, err := build.ImportDir(dir, 0)
	if err != nil {
		return nil, fmt.Errorf("read Go package: %w", err)
	}
	names := slices.Concat(pkg.GoFiles, pkg.CgoFiles, pkg.TestGoFiles, pkg.XTestGoFiles)
	slices.Sort(names)
	fset := token.NewFileSet()
	files := make([]*ast.File, 0, len(names))
	for _, name := range names {
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", name, err)
		}
		if file.Doc != nil && strings.HasPrefix(file.Doc.Text(), "Code generated ") {
			file.Doc = nil
		}
		files = append(files, file)
	}

	p, err := doc.NewFromFiles(fset, files, importPath, doc.AllMethods)
	if err != nil {
		return nil, fmt.Errorf("extract Go documentation: %w", err)
	}
	r := renderer{fset: fset, parser: p.Parser(), printer: p.Printer()}
	r.printer.HeadingLevel = 5
	r.printer.HeadingID = func(*comment.Heading) string { return "" }
	r.printer.DocLinkURL = func(link *comment.DocLink) string {
		if link.ImportPath != "" && link.ImportPath != importPath {
			return link.DefaultURL("https://pkg.go.dev")
		}
		name := link.Name
		if link.Recv != "" {
			name = link.Recv + "." + name
		}
		if name == "" {
			return "#go-api-reference"
		}
		return "#" + anchor(name)
	}

	r.text("# Go API reference\n\n")
	r.text("<!-- Generated by go/internal/docgen from Go source. DO NOT EDIT. -->\n\n")
	r.text("Package `" + importPath + "`.\n\n")
	r.text("Generated from the exported Go declarations and doc comments, including " +
		"client methods, models, helpers, and test doubles. " +
		"See the [Go client guide](api.md) for usage.\n\n")
	r.description(p.Doc)
	r.examples(p.Examples)

	r.values("Constants", p.Consts)
	r.values("Variables", p.Vars)
	if len(p.Funcs) > 0 {
		r.text("## Functions\n\n")
		for _, fn := range p.Funcs {
			r.function(fn, fn.Name, 3)
		}
	}

	if len(p.Types) > 0 {
		r.text("## Types\n\n")
	}
	for _, typ := range p.Types {
		r.heading(typ.Name, "type "+typ.Name, 3)
		r.description(typ.Doc)
		r.declaration(typ.Decl)
		r.examples(typ.Examples)
		for _, value := range slices.Concat(typ.Consts, typ.Vars) {
			r.value(value, 4)
		}
		for _, fn := range typ.Funcs {
			r.function(fn, fn.Name, 4)
		}
		for _, method := range typ.Methods {
			r.function(method, typ.Name+"."+method.Name, 4)
		}
	}
	if r.err != nil {
		return nil, r.err
	}
	return []byte(r.page.String()), nil
}

type renderer struct {
	fset    *token.FileSet
	parser  *comment.Parser
	printer *comment.Printer
	page    strings.Builder
	err     error
}

func anchor(name string) string {
	return "go-" + strings.ToLower(strings.ReplaceAll(name, ".", "-"))
}

func (r *renderer) text(text string) {
	r.page.WriteString(text)
}

func (r *renderer) heading(name, title string, level int) {
	r.text("(" + anchor(name) + ")=\n")
	r.text(strings.Repeat("#", level) + " " + title + "\n\n")
}

func (r *renderer) description(text string) {
	if text != "" {
		r.text(string(r.printer.Markdown(r.parser.Parse(text))) + "\n")
	}
}

func (r *renderer) code(language, code string) {
	fence := "```"
	for strings.Contains(code, fence) {
		fence += "`"
	}
	r.text(fence + language + "\n" + strings.TrimSpace(code) + "\n" + fence + "\n\n")
}

func (r *renderer) declaration(node ast.Node) {
	// Keep field comments and tags, but omit duplicated declaration comments
	// and function implementations from the reference signatures.
	switch decl := node.(type) {
	case *ast.FuncDecl:
		copy := *decl
		copy.Doc = nil
		copy.Body = nil
		node = &copy
	case *ast.GenDecl:
		copy := *decl
		copy.Doc = nil
		node = &copy
	}
	var code bytes.Buffer
	if err := format.Node(&code, r.fset, node); err != nil {
		r.err = fmt.Errorf("format declaration: %w", err)
		return
	}
	r.code("go", code.String())
}

func (r *renderer) values(title string, values []*doc.Value) {
	if len(values) == 0 {
		return
	}
	r.text("## " + title + "\n\n")
	for _, value := range values {
		r.value(value, 3)
	}
}

func (r *renderer) value(value *doc.Value, level int) {
	for _, name := range value.Names[1:] {
		r.text("(" + anchor(name) + ")=\n")
	}
	title := value.Decl.Tok.String() + " " + value.Names[0]
	if len(value.Names) > 1 {
		title += " (group)"
	}
	r.heading(value.Names[0], title, level)
	r.description(value.Doc)
	r.declaration(value.Decl)
}

func (r *renderer) function(fn *doc.Func, name string, level int) {
	r.heading(name, name, level)
	r.description(fn.Doc)
	r.declaration(fn.Decl)
	r.examples(fn.Examples)
}

func (r *renderer) examples(examples []*doc.Example) {
	for _, example := range examples {
		r.text("**Example")
		if example.Suffix != "" {
			r.text(" (" + example.Suffix + ")")
		}
		r.text("**\n\n")
		r.description(example.Doc)
		if example.Play != nil {
			r.declaration(example.Play)
		} else {
			r.declaration(example.Code)
		}
		if example.Output != "" || example.EmptyOutput {
			r.text("Output:\n\n")
			r.code("text", example.Output)
		}
	}
}
