    async def inspect_instance_grep(
        self,
        operation_uuid: str,
        pattern: str | Sequence[str],
        *,
        path: str | Sequence[str] | None = None,
        glob: str | Sequence[str] | None = None,
        max_count: int | None = None,
        max_total: int | None = None,
        case: Literal["sensitive", "insensitive", "smart"] | None = None,
        before: int | None = None,
        after: int | None = None,
    ) -> GrepResult:
        """Search file contents in running instance.

        Regex content search inside the running instance's root filesystem,
        through guest RPC.
        A Go converter translates supported Rust regex syntax to Go regexp.

        Symlinks are never followed during traversal, hidden files are searched,
        ``.ignore`` and ``.gitignore`` rules within each search root are
        respected.
        A NUL byte in the first 64 KiB causes a file to be skipped; a later NUL
        ends that file's search. Go regexp uses linear-time matching.
        The classes \\w/\\W, \\d/\\D, and \\s/\\S use Unicode semantics.
        Unicode properties and case folding are pinned to Unicode 16.0.0,
        matching the image engine.
        Scoped flags, nested class set operations, and bounded expansion of
        large repetitions are supported.
        Expanded patterns share a 1 MiB limit per request. Unsupported syntax
        returns 400 with a pattern
        index and byte offset. Unicode \\b/\\B, CRLF mode, non-ASCII byte mode,
        and \\Q…\\E are rejected.
        Use (?-u:\\b) for an ASCII word boundary. Smart case examines parsed
        literals.

        Results are a flat, file-ordered list of lines. ``before``/``after``
        request extra
        ``type: context`` lines around each ``type: match`` line, mirroring
        ripgrep's
        --json message type field.

        ``path`` may be repeated to search multiple roots in one call, the same
        way
        ``pattern``/``glob`` already can; results are concatenated in the given
        order
        and share the ``max_total`` budget across all of them.
        Results never enter operation events. Reads are live and do not form a
        snapshot.
        procfs, sysfs, devices, sockets, and FIFOs are not searched.
        Requires LIST and the permission used to start this instance.
        Searches have a 10-second budget per root and permit two concurrent
        searches per instance. Reaching the time, depth, or result limit sets
        ``truncated``. Context lines count towards ``max_total``. Display text
        is
        limited to 4096 bytes per line; matching can continue beyond this
        window.

        Args:
            operation_uuid: The UUID of the running instance to inspect
                Example: ``12345678-9abc-baba-deda-0123456789ab``.
            pattern: Regex pattern to search for. May be repeated (max 16);
                patterns are OR-ed. Max 1024 characters each. Example:
                ``^PermitRootLogin``.
            path: File or directory to search inside the running instance.
                May be repeated (max 16) to search multiple roots; results
                are concatenated in the given order, sharing max_total
                across all paths. Defaults to the rootfs root. Example:
                ``/etc``.
            glob: Glob to filter files (ripgrep -g semantics, "!" negates).
                May be repeated. Example: ``*.conf``.
            max_count: Maximum matches per file (hard cap 10000).
            max_total: Maximum total matches across all files (default 1000,
                hard cap 10000).
            case: Case sensitivity mode.
            before: Lines of context to include before each match (ripgrep
                -B semantics, hard cap 50). For symmetric context (grep -C
                n), pass both before and after yourself.
            after: Lines of context to include after each match (ripgrep -A
                semantics, hard cap 50).
        """
        spec = operations.build_inspect_instance_grep(
            operation_uuid=operation_uuid,
            pattern=pattern,
            path=path,
            glob=glob,
            max_count=max_count,
            max_total=max_total,
            case=case,
            before=before,
            after=after,
        )
        self.log_request(spec)
        response = await self.call(spec)
        self.log_response(spec, response)
        return operations.parse_inspect_instance_grep(response)

