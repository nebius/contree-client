    def apply_instance_file(
        self,
        operation_uuid: str,
        file_uuid: str,
        path: str,
        *,
        unpack: bool | EllipsisType = ...,
        replace: bool | EllipsisType = ...,
        merge: bool | EllipsisType = ...,
    ) -> None:
        """Apply an uploaded file to a running instance.

        Reads a file previously uploaded through POST /files and writes it to a
        running INSTANCE operation, including disposable instances. Requires
        LIST
        and the permission used to start the instance. Both the operation and
        the
        uploaded file must belong to the request namespace. Expired files are
        unavailable.
        The assigned worker streams the stored object to the guest through RPC.
        Init records request metadata in ``inspect`` events and the terminal
        publication result in ``file_upload``, including ``file_uuid`` and byte
        count.
        File contents do not enter operation events.

        With unpack omitted or false, path is the full destination filename.
        Missing parent directories are created. The file is published atomically
        after
        transfer and SHA256 verification. The new file has mode 0644 and is
        owned by the guest runtime user. With replace true, an existing leaf
        symlink is replaced.
        Directories and special files are not regular file destinations.

        With unpack true, path is the destination directory. Supports tar,
        tar.gz and tar.bz2; compression is detected from the stored bytes. Xz is
        unsupported and rejected before subsequent chunks are sent. Without
        unpack,
        compressed archives are copied unchanged. Content-Type describes this
        JSON
        request and never controls extraction.

        Extraction accepts regular files, directories, symlinks and hardlinks to
        regular files already extracted in the staging tree. Parent symlinks
        inside that tree are
        not followed. Absolute entry names and entries containing '..' are
        rejected.
        procfs, sysfs, devices, FIFOs and sockets are unsupported. New
        directories
        have mode 0755; regular files retain tar permission bits (0777).
        Ownership
        and timestamps are not restored. Other entries fail explicitly.
        With replace omitted or false, any existing destination returns 409,
        including
        a symlink or empty directory. This condition is checked again atomically
        at publication.
        replace true permits an existing destination. With merge omitted or
        false,
        directory replacement removes the entire old tree without merging
        contents.

        Archives are extracted into a temporary sibling directory. The
        destination
        remains unchanged until the complete stream and SHA256 have been
        verified.
        Without merge, publication uses an atomic rename or exchange, then
        removes the old tree.
        Root and mount-point replacement are unavailable. Existing open
        descriptors
        can still refer to old inodes; concurrent workload access is not a
        snapshot.

        merge true requires both unpack true and replace true. After complete
        staging
        and verification, it combines directories and atomically replaces
        individual
        files and symlinks. Existing entries absent from the archive remain.
        Destination
        directory symlinks are not followed; directory/file conflicts fail
        explicitly.
        Same-filesystem hardlinks are retained. Crossing a destination mount
        requires
        copying file bytes and does not preserve hardlinks across filesystems.
        Merge is not atomic for the whole tree: errors, cancellation or timeout
        after
        application starts can leave completed changes. These changes are not
        rolled back.

        Returns 204 only after completion. Transfers have a 300-second deadline
        and bounded buffers and handles. Disconnect or VM exit cancels the
        transfer.
        A lost response can leave an uncertain outcome; requests are not
        replayed
        automatically. This endpoint does not write to a completed result image.

        A transfer timeout does not stop the instance. Before publication or
        merge starts, cancellation
        preserves the old destination and removes the temporary file or
        extraction tree.
        A timeout while awaiting the final response can occur after publication;
        it does not prove that no changes were made. An old-tree cleanup failure
        is
        reported as an error after publication; it does not roll back the new
        tree.
        The uploaded source object retains its normal lifetime. Automatically
        created
        parent directories have mode 0755 and can remain after errors.

        The primary command's timeout follows normal instance finalization:
        ordinary
        instances persist their filesystem, including successfully published
        uploads;
        disposable instances do not. Instance shutdown waits for pending upload
        cleanup.
        A timeout or crash of the execution environment can bypass this cleanup
        and does not produce
        a successfully persisted result image through normal finalization.

        Args:
            operation_uuid: Example:
                ``12345678-9abc-baba-deda-0123456789ab``.
            path: Absolute guest filename, or directory when unpack is true.
                Missing parents are created.
            unpack: Extract tar, tar.gz or tar.bz2 instead of copying the
                stored bytes.
            replace: Permit an existing destination. Without merge,
                directories are replaced in full.
            merge: Merge verified archive contents. Requires unpack and
                replace. Can leave partial changes.
        """
        spec = operations.build_apply_instance_file(
            operation_uuid=operation_uuid,
            file_uuid=file_uuid,
            path=path,
            unpack=unpack,
            replace=replace,
            merge=merge,
        )
        self.log_request(spec)
        response = self.call(spec)
        self.log_response(spec, response)
        return operations.parse_apply_instance_file(response)

