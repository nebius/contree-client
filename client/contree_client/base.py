    async def iter_operation_events(
        self,
        operation_id: str,
        *,
        follow: bool = False,
        spid: int | None = None,
        since: int | None = None,
        last_event_id: int | None = None,
        deadline: float | None = None,
        idle_timeout: float = 0.0,
    ) -> AsyncGenerator[OperationEvent, None]:
        """Stream the operation event log via Server-Sent Events.

        Always returns ``text/event-stream`` (SSE) on success.  The body
        is a sequence of three kinds of lines (per RFC W3C SSE), each
        terminated by ``\\n\\n``:

        .. rubric:: Frame shapes


        **Normal event frame** — one ``OperationEvent`` JSON object in
        ``data:``, dispatchable via ``event:``:

        ::

            id: <integer event.id>
            event: <OperationEventType, e.g. stdout|stderr|spawn|exit>
            data: {"id": N, "ts": "...", "spid": ..., "type": "...", "data": {...}}

        ``event:`` always matches ``data.type``.  See ``OperationEvent`` and
        ``OperationEventType`` for the per-type payload shape.  Native
        ``EventSource`` dispatches each frame to the matching
        ``addEventListener("<type>", ...)`` handler.

        **Server-side error frame** — surfaces handler exceptions to
        the connected client without tearing the TCP connection down
        mid-stream.  Sent right before the server closes the response:

        ::

            : stream ended with error, retry since last event id

            event: sse_error
            data: <one-line exception message>

        The leading SSE comment line lets pure-EventSource clients see
        the intent ("retry from Last-Event-Id"); the ``sse_error`` frame
        carries the error text for logging.  Clients should treat this
        as a non-clean close and reconnect with the standard SSE
        ``Last-Event-Id`` semantics (see Resuming).

        **Keepalive comment** — periodic ``: keepalive\\n\\n`` lines
        emitted while the stream is idle.  They keep upstream
        ``proxy_read_timeout`` / TCP idle timers fresh and have no
        application meaning.  Spec-compliant; EventSource and any SSE
        parser must ignore comment lines (those beginning with ``:``).

        .. rubric:: ``follow`` semantics


        The ``follow`` parameter controls only whether the stream stays
        open after the last currently-known event:

          * ``follow=0`` (default) — the server emits everything
            currently available and closes the connection.

          * ``follow=1`` — same start; if the operation is still
            running the server keeps the connection open and forwards
            new events as they appear.  For terminal operations
            ``follow=1`` is a no-op: there's nothing more to subscribe
            to, so the connection closes after the last event just
            like ``follow=0``.

        Optional filters:

          * ``?spid=N`` — only events whose ``spid`` (Spawned Process ID,
            the routing identity in ``OperationEvent``) matches.

          * ``?since=N`` — only events with ``id > N``.

        ``follow=1`` requires ``SPAWN`` or ``SPAWN_DISPOSABLE`` on top of
        the baseline ``LIST`` — a long-lived subscription reserves
        per-operation server state.  ``follow=0`` is read-only and
        stays under ``LIST``.

        .. rubric:: Resuming after a drop


        Every normal frame carries ``id:`` — the canonical event id.
        On reconnect send the last successfully received id in the
        standard ``Last-Event-Id`` request header (or ``?since=N`` on
        manual GETs); the server resumes from that point.

        .. rubric:: Error handling


        .. list-table::
           :header-rows: 1

           * - Status
             - Meaning
             - Client action
           * - 200
             - Stream open
             - Read frames; reconnect with Last-Event-Id if the stream closes
               before reaching a terminal event
           * - 400
             - Malformed query/header (non-integer param)
             - Fix request
           * - 401
             - Missing/invalid auth
             - Refresh credentials
           * - 403
             - Auth lacks LIST (or SPAWN for ``follow=1``)
             - Use a token with the right scope
           * - 404
             - Operation not in this namespace
             - Wrong UUID
           * - 410
             - Stream is over but the terminal artifact isn't ready yet
             - Retry after ``Retry-After``
           * - 425
             - Not yet ready (operation is still being prepared)
             - Retry after ``Retry-After``
           * - 502
             - Upstream returned an error opening the stream
             - Retry; if persistent, escalate
           * - 504
             - Upstream took too long to respond
             - Retry


        A ``200`` followed by an ``event: sse_error`` frame and immediate
        close is the in-band equivalent of "the stream broke after we
        already committed to a 200" — handle it the same way as 410:
        wait briefly, reconnect with ``Last-Event-Id``.

        See ``OperationEvent`` for the per-event shape.

        Args:
            operation_id: The ID of the operation Example:
                ``12345678-9abc-baba-deda-0123456789ab``.
            follow: HTTP-flag boolean. Present without a value (``?follow``)
                and ``?follow=1`` both enable; ``?follow=0`` and absence
                disable. When enabled, the SSE stream stays open after the
                currently-known events have been sent — for a running
                operation new events are forwarded as they appear; for a
                terminal operation it has no effect.
            spid: Only emit events whose ``spid`` field matches. Filter is
                applied server-side regardless of whether the operation is
                still running or already terminal.
            since: Only emit events with ``id > since`` (event IDs are
                monotonically increasing). Overridden by the
                ``Last-Event-Id`` header when present.
            last_event_id: Standard SSE resume header sent automatically by
                ``EventSource`` on reconnect. Treated as ``?since=N``; takes
                precedence over the query param.
            deadline: absolute monotonic deadline. Checked whenever
                iteration resumes; caller code between events is not
                interrupted.
            idle_timeout: seconds without incoming data before a transport
                timeout; 0 disables it
        """
        spec = operations.build_iter_operation_events(
            operation_id=operation_id,
            follow=follow,
            spid=spid,
            since=since,
            last_event_id=last_event_id,
        )
        if not math.isfinite(idle_timeout) or idle_timeout < 0:
            raise ValueError("idle_timeout must be finite and non-negative")
        spec.read_timeout = idle_timeout or None
        spec.deadline = deadline
        if deadline is not None:
            spec.read_timeout = min(
                spec.read_timeout or math.inf, max(0.0, deadline - time.monotonic())
            )
        self.log_request(spec)
        parser = SSEParser()
        last_seen = last_event_id
        async with aclosing(self.stream(spec)) as source:
            async for chunk in source:
                if deadline is not None and time.monotonic() >= deadline:
                    raise TimeoutError("iter_operation_events exceeded its deadline")
                for frame in parser.feed(chunk):
                    if frame.id is not None:
                        last_seen = frame.id
                    event = decode_event_frame(frame, last_seen)
                    if event is None:
                        continue
                    self.log.debug("sse event: %r", event)
                    yield event
                    if deadline is not None and time.monotonic() >= deadline:
                        raise TimeoutError(
                            "iter_operation_events exceeded its deadline"
                        )

    async def operation_subprocess_create(
        self,
        operation_id: str,
        command: str,
        *,
        resources_limits: ProcessResourcesLimits | EllipsisType = ...,
        args: list[str] | EllipsisType = ...,
        shell: bool | EllipsisType = ...,
        env: dict[str, str] | None | EllipsisType = ...,
        cwd: str | EllipsisType = ...,
        uid: int | EllipsisType = ...,
        gid: int | EllipsisType = ...,
        stdin: ClosableStreamRepr | EllipsisType = ...,
        truncate_output_at: int | EllipsisType = ...,
    ) -> int:
        """Spawn an additional subprocess inside a running instance.

        Starts a new process inside the VM that already hosts the named
        operation.  Distinct from ``POST /instances``, which spins up a
        VM: this endpoint requires a running operation (EXECUTING or
        ASSIGNED) and reuses the existing VM.

        The body is an ``ExecSpec`` — process-execution fields only.
        VM-level concerns (``image``, ``hostname``,
        ``files``, ``timeout``, ``disposable``, ``preserve_env``) are not
        accepted here; they were set when the parent operation was
        created.

        ``resources_limits.cpu`` and ``resources_limits.memory_mib`` use the
        same names and units as operation creation. Each omitted or null
        subprocess limit inherits the corresponding operation limit.
        Values above the operation limit return 400. Limits apply at
        launch: memory_mib sets RLIMIT_AS for each process and memory.max
        for the entire process tree. They cannot be changed through this
        API. Guest root can modify limits; these limits do not
        provide security isolation between processes in one VM.

        The required permission follows the parent instance:
        ``SPAWN_DISPOSABLE`` when it was spawned with ``disposable=true``,
        ``SPAWN`` otherwise.

        On success the worker assigns a fresh ``spid`` (≥2; ``spid=1`` is
        the main process spawned from ``metadata``) and the response
        carries it in the body plus a ``Location`` header pointing at
        ``GET /operations/{operationId}/subprocesses/{spid}`` — the
        subprocess result reconstructed from its events.

        Args:
            operation_id: The ID of the operation Example:
                ``12345678-9abc-baba-deda-0123456789ab``.
            command: The command to execute. Same semantics as in
                ``InstanceSpawnRequest.command`` — when ``shell=true`` it is
                a shell expression, otherwise a path to an executable.
                Example: ``/bin/app``.
            args: Arguments to pass to the command if shell is set to false.
                Example: ``["arg1","arg2"]``.
            shell: Run command through a shell expression (args must be
                empty).
            env: Environment variables to set in the child process.
            cwd: Working directory; empty string means image / server
                default.
            uid: User ID to run the process as.
            gid: Group ID to run the process as.
            stdin: Bytes fed to the child's stdin — honored for both the
                main process and exec'd subprocesses. With ``close=false``
                the pipe stays open and more data can be written via
                ``POST /operations/{operationId}/subprocesses/{spid}/stdin``.
            truncate_output_at: Maximum number of bytes to keep per stream
                (stdout, stderr, and stdin) in the subprocess event log.
                Does not affect delivery to the child — stdin is always
                delivered in full regardless of this cap. Defaults to 1 MiB;
                capped at 10 MiB. Example: ``65535``.
        """
