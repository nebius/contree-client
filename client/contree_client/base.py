class ContreeAsyncClient(ContreeClientBase, ABC):
    """Asynchronous Contree API client interface.

    Backend implementations only provide :meth:`request`,
    :meth:`stream` and :meth:`close`.
    """

    @abstractmethod
    async def request(self, spec: RequestSpec) -> ResponseData:
        """Execute the request and return the buffered response."""

    @abstractmethod
    def stream(
        self,
        spec: RequestSpec,
        auto_decompress: bool = True,
    ) -> AsyncGenerator[bytes, None]:
        """Execute the request and yield response body chunks.

        With ``auto_decompress=False`` the body is yielded exactly as
        served (e.g. the gzip the server always applies is kept).
        """

    @abstractmethod
    async def close(self) -> None:
        """Release the underlying transport resources."""

    async def open(self) -> None:
        """Eagerly initialize the underlying transport.

        Called by ``__aenter__`` from inside the running event loop,
        so backends can create loop-bound resources here (for example
        the ``aiohttp.ClientSession``). The default is a no-op.
        """

    async def __aenter__(self: TAsyncClient) -> TAsyncClient:
        await self.open()
        return self

    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        await self.close()

    async def call(self, spec: RequestSpec) -> ResponseData:
        """Execute a buffered request, retrying per the client policy.

        Without a policy this is a transparent single :meth:`request`.
        Streaming requests are never routed here - SSE consumers
        reconnect with ``Last-Event-Id`` instead.
        """
        policy = self.retry
        if policy is None:
            if spec.deadline is not None:
                remaining = spec.deadline - time.monotonic()
                if remaining <= 0:
                    raise TimeoutError(REQUEST_DEADLINE_MESSAGE)
            deadline_limited = deadline_limits_timeout(spec.deadline, self.timeout)
            try:
                if spec.deadline is None:
                    response = await self.request(spec)
                else:
                    response = await asyncio.wait_for(
                        self.request(spec), timeout=remaining
                    )
            except APIConnectionError as exc:
                if deadline_due(spec.deadline, deadline_limited and exc.timed_out):
                    raise TimeoutError(REQUEST_DEADLINE_MESSAGE) from exc
                raise
            except (asyncio.TimeoutError, TimeoutError) as exc:
                if spec.deadline is not None:
                    raise TimeoutError(REQUEST_DEADLINE_MESSAGE) from exc
                raise
            if spec.deadline is not None and time.monotonic() >= spec.deadline:
                raise TimeoutError(REQUEST_DEADLINE_MESSAGE)
            return response
        # a lost response after a non-idempotent request (POST) could
        # mean a second execution server-side: never blind-retry
        # unless the caller explicitly opted into that risk. 425 Too
        # Early and 429 Too Many Requests are the exceptions - the
        # backend's contract guarantees both mean the request was
        # rejected before any processing, so replaying is always safe.
        replay_safe = spec.idempotent or policy.retry_unsafe
        delays = retry_generator(policy.delays)
        # a retry must replay exactly the bytes the first attempt sent
        start = body_start(spec)
        attempts = 0
        while True:
            if spec.deadline is not None:
                remaining = spec.deadline - time.monotonic()
                if remaining <= 0:
                    raise TimeoutError(REQUEST_DEADLINE_MESSAGE)
            attempts += 1
            exhausted = (
                policy.max_attempts is not None and attempts >= policy.max_attempts
            )
            deadline_limited = deadline_limits_timeout(spec.deadline, self.timeout)
            try:
                if spec.deadline is None:
                    response = await self.request(spec)
                else:
                    response = await asyncio.wait_for(
                        self.request(spec), timeout=remaining
                    )
            except APIConnectionError as exc:
                if deadline_due(spec.deadline, deadline_limited and exc.timed_out):
                    raise TimeoutError(REQUEST_DEADLINE_MESSAGE) from exc
                if not replay_safe or exhausted:
                    raise
                delay = next(delays)
                self.log.warning(
                    "network error (%s), retrying in %.1fs...",
                    type(exc).__name__,
                    delay,
                )
                if spec.deadline is not None:
                    delay = min(
                        delay,
                        max(0.0, spec.deadline - time.monotonic()),
                    )
                await asyncio.sleep(delay)
                rewind_body(spec, start)
                continue
            except APIStatusError as exc:
                if not policy.retryable_status(exc.status) or exhausted:
                    raise
                if not replay_safe and exc.status not in (425, 429):
                    raise
                delay = exc.retry_after
                if delay is None:
                    delay = next(delays)
                self.log.warning(
                    "server answered %d, retrying in %.1fs...",
                    exc.status,
                    delay,
                )
                if spec.deadline is not None:
                    delay = min(
                        delay,
                        max(0.0, spec.deadline - time.monotonic()),
                    )
                await asyncio.sleep(delay)
                rewind_body(spec, start)
                continue
            except (asyncio.TimeoutError, TimeoutError) as exc:
                if spec.deadline is not None:
                    raise TimeoutError(REQUEST_DEADLINE_MESSAGE) from exc
                raise
            if spec.deadline is not None and time.monotonic() >= spec.deadline:
                raise TimeoutError(REQUEST_DEADLINE_MESSAGE)
            return response

    async def operation_terminal(
        self,
        operation_id: str,
        deadline: float | None = None,
    ) -> bool:
        """Best-effort check that the operation reached a terminal state."""
        spec = operations.build_get_operation_status(operation_id=operation_id)
        spec.deadline = deadline
        deadline_limited = deadline_limits_timeout(deadline, self.timeout)
        try:
            self.log_request(spec)
            if deadline is None:
                response = await self.request(spec)
            else:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise TimeoutError(
                        f"operation {operation_id} status probe exceeded its deadline"
                    )
                response = await asyncio.wait_for(self.request(spec), timeout=remaining)
            if deadline is not None and time.monotonic() >= deadline:
                raise TimeoutError(
                    f"operation {operation_id} status probe exceeded its deadline"
                )
            self.log_response(spec, response)
            status = operations.parse_get_operation_status(response).status
        except APIConnectionError as exc:
            if deadline_due(deadline, deadline_limited and exc.timed_out):
                raise TimeoutError(
                    f"operation {operation_id} status probe exceeded its deadline"
                ) from exc
            return False
        except APIStatusError as exc:
            if deadline_due(deadline):
                raise TimeoutError(
                    f"operation {operation_id} status probe exceeded its deadline"
                ) from exc
            if exc.status in (410, 425, 429) or exc.status >= 500:
                return False
            raise
        except (asyncio.TimeoutError, TimeoutError) as exc:
            if deadline is not None:
                raise TimeoutError(
                    f"operation {operation_id} status probe exceeded its deadline"
                ) from exc
            raise
        return not isinstance(status, EllipsisType) and status.is_terminal()

    async def _read_operation_status(
        self,
        operation_id: str,
        deadline: float | None,
    ) -> OperationResponse:
        """Fetch status using the waiter's deadline."""
        spec = operations.build_get_operation_status(operation_id=operation_id)
        spec.deadline = deadline
        self.log_request(spec)
        response = await self.call(spec)
        self.log_response(spec, response)
        return operations.parse_get_operation_status(response)

    async def wait_operation(
        self,
        operation_id: str,
        *,
        timeout: float | None = None,
        follow_events: bool | None = None,
        idle_timeout: float = 15.0,
    ) -> OperationResponse:
        """Wait for the terminal operation response.

        ``follow_events=None`` follows instance events and polls image imports
        every 0.5 seconds. Use ``True`` to force events or ``False`` to force
        polling. Keep the event stream open until completion, EOF, a transport
        error, or a timeout. ``idle_timeout`` is the maximum gap between
        incoming data chunks in seconds (default 15.0; 0 disables it).
        Ping/keepalive traffic resets this limit; it does not extend the
        overall timeout. Gaps between payload events do not trigger checks.
        After completion, poll until the status is terminal.
        Return failed and cancelled responses unchanged.
        ``timeout`` covers the entire wait and raises :class:`TimeoutError`
        on expiry.
        """
        if not math.isfinite(idle_timeout) or idle_timeout < 0:
            raise ValueError("idle_timeout must be finite and non-negative")
        deadline = None if timeout is None else time.monotonic() + timeout
        timeout_message = f"operation {operation_id} did not complete within {timeout}s"
        try:
            result = None
            if follow_events is None:
                result = await self._read_operation_status(operation_id, deadline)
                follow_events = result.kind != "image_import"
            if follow_events:
                remaining = (
                    None if deadline is None else max(0.0, deadline - time.monotonic())
                )
                async for event in self.follow_operation_events(
                    operation_id, timeout=remaining, idle_timeout=idle_timeout
                ):
                    self.log.debug("wait_operation: event %s %s", event.id, event.type)
                result = await self._read_operation_status(operation_id, deadline)

            if result is None:
                result = await self._read_operation_status(operation_id, deadline)
            while True:
                if (
                    not isinstance(result.status, EllipsisType)
                    and result.status.is_terminal()
                ):
                    return result
                delay = TIGHT_LOOP_FLOOR
                if deadline is not None:
                    delay = min(delay, max(0.0, deadline - time.monotonic()))
                await asyncio.sleep(delay)
                result = await self._read_operation_status(operation_id, deadline)
        except (asyncio.TimeoutError, TimeoutError) as exc:
            if deadline is not None:
                raise TimeoutError(timeout_message) from exc
            raise

    async def follow_operation_events(
        self,
        operation_id: str,
        *,
        last_event_id: int | None = None,
        spid: int | None = None,
        since: int | None = None,
        timeout: float | None = None,
        idle_timeout: float = 15.0,
    ) -> AsyncGenerator[OperationEvent, None]:
        """Stream operation events with transparent reconnection.

        Native stream failures trigger a terminal-status probe and a
        reconnect from the last event id. Iteration ends at the
        ``completion`` event or the timeout. After a terminal status,
        drain the retained log without following before ending iteration.
        Interrupted retained reads resume from the last event id, using
        the configured retry policy (three attempts by default). Normal
        EOF also completes a filtered or explicitly resumed retained log.
        An unfiltered log must include completion. An unavailable or
        incomplete event log raises APIConnectionError.
        The timeout is an absolute deadline checked whenever iteration
        resumes. Caller code between events is not interrupted.
        ``idle_timeout`` bounds gaps between incoming data in seconds
        (default 15.0; 0 disables it). Ping/keepalive traffic resets this
        limit without extending the overall timeout.
        """
        if not math.isfinite(idle_timeout) or idle_timeout < 0:
            raise ValueError("idle_timeout must be finite and non-negative")
        last_id = last_event_id
        terminal = False
        drain_attempts = 0
        policy = self.retry or RetryPolicy(max_attempts=3)
        delays = retry_generator(policy.delays)
        deadline = None if timeout is None else time.monotonic() + timeout

        def check_deadline() -> None:
            if deadline_due(deadline):
                raise TimeoutError(
                    f"operation {operation_id} events did not complete"
                    f" within {timeout}s"
                )

        while True:
            check_deadline()
            events_before = last_id
            if terminal:
                drain_attempts += 1
            try:
                # aclosing: leaving this scope must close the transport
                # stream even when the caller aborts the iteration
                async with aclosing(
                    self.iter_operation_events(
                        operation_id,
                        follow=not terminal,
                        spid=spid,
                        since=since,
                        last_event_id=last_id,
                        deadline=deadline,
                        idle_timeout=idle_timeout,
                    )
                ) as source:
                    async for event in source:
                        last_id = event.id
                        yield event
                        if event.type == "completion":
                            return
                        check_deadline()
            except (APIConnectionError, APIStatusError) as exc:
                check_deadline()
                retryable = not isinstance(exc, APIStatusError) or (
                    policy.retryable_status(exc.status)
                )
                resume_id = getattr(exc, "last_event_id", None)
                if isinstance(resume_id, int):
                    last_id = resume_id
                self.log.warning("stream broken (last_id=%s): %s", last_id, exc)
                if not retryable or (
                    terminal
                    and policy.max_attempts is not None
                    and drain_attempts >= policy.max_attempts
                ):
                    raise APIConnectionError(
                        f"operation {operation_id} event log could not be read"
                    ) from exc
                if terminal:
                    retry_at = time.monotonic() + next(delays)
                    if deadline is not None:
                        retry_at = min(retry_at, deadline)
                    # asyncio timers can wake early on coarse-resolution clocks.
                    while True:
                        await asyncio.sleep(max(0.0, retry_at - time.monotonic()))
                        if time.monotonic() >= retry_at:
                            break
                    continue
            else:
                if terminal:
                    if spid is None and since is None and last_event_id is None:
                        raise APIConnectionError(
                            f"operation {operation_id} event log"
                            " ended without completion"
                        )
                    return
            # A terminal status does not mean this subscriber received all
            # events. Reconnect to drain the retained tail, retaining
            # the cursor, filters and original deadline.
            terminal = await self.operation_terminal(operation_id, deadline)
            if not terminal and last_id == events_before:
                delay = TIGHT_LOOP_FLOOR
                if deadline is not None:
                    delay = min(delay, max(0.0, deadline - time.monotonic()))
                await asyncio.sleep(delay)

