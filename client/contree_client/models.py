@dataclass
class EventDataStream(ContreeModel):
    """Payload for ``stdin`` / ``stdout`` / ``stderr`` events.  Encoding.

    is ``ascii`` when every byte is printable plus ``\\\\n`` / ``\\\\r``
    / ``\\\\t``; ``base64`` otherwise.  Chunks are at most a few KB
    each — the natural read granularity from a pipe.
    """

    value: str = field(metadata={"example": "hello world\n"})
    encoding: Literal["ascii", "base64"] = field(metadata={"example": "ascii"})
    truncated: bool | EllipsisType = field(
        default=...,
        metadata={
            "description": (
                "Always `false` on per-chunk stream events.  When a stream\ncrosses "
                "its per-stream cap a separate `truncated`-type\nevent is emitted on "
                "EOF carrying the cumulative\nemitted/dropped totals."
            ),
            "example": False,
        },
    )

    def as_bytes(self) -> bytes:
        """The payload decoded to raw bytes.

        ``base64`` values are decoded; ``ascii`` text is UTF-8
        encoded. Undecodable base64 becomes empty bytes instead of
        failing a live stream.
        """
        if not self.value:
            return b""
        if self.encoding == "base64":
            try:
                return base64.b64decode(self.value)
            except (binascii.Error, ValueError):
                return b""
        return self.value.encode("utf-8", errors="replace")

    def as_text(self) -> str:
        """The payload decoded to text (UTF-8, errors replaced)."""
        if self.encoding == "base64":
            return self.as_bytes().decode("utf-8", errors="replace")
        return self.value

    @classmethod
    def from_bytes(cls, value: bytes) -> EventDataStream:
        """Build a payload from raw bytes.

        Printable ASCII (plus tab/newline/carriage return) is stored
        as ``ascii``; anything else is base64-encoded - the same rule
        the server applies on its side.
        """
        if all(32 <= byte < 127 or byte in (9, 10, 13) for byte in value):
            return cls(value=value.decode("ascii"), encoding="ascii")
        return cls(
            value=base64.b64encode(value).decode("ascii"),
            encoding="base64",
        )

    @classmethod
    def from_text(cls, value: str) -> EventDataStream:
        """Build a payload from text (UTF-8 encoded unless ASCII)."""
        return cls.from_bytes(value.encode("utf-8"))


